"""Find bundles on disk, load their cards, and check them against the code.

A **bundle** is a directory under ``metrics/`` or ``degradations/`` holding one metric or
one degradation and everything that documents it. This module is the only place that
knows the directory layout; everything else asks here.

Where enforcement happens, and why not at import
------------------------------------------------
The obvious way to make a card unskippable is to validate it when the module is imported,
so a bundle without a card cannot even load. That is rejected here for a specific reason:
discovery imports *every* module in the package, so a colleague's half-finished card in
one bundle would break ``evaluate.py`` for everyone running an unrelated metric. It would
also make ``metrics/`` depend on this package, which imports pandas and matplotlib, when
today it needs only numpy.

Instead the registries expose a validation hook that this module installs. Asking for a
metric by name validates *that* metric's card, so you cannot run something undocumented,
while an unrelated broken card stays a broken card. The parametrized tests in
``tests/test_cards.py`` check all bundles at once, which is where a repository-wide
problem should surface.
"""

from __future__ import annotations

import json
import os
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

from degradations import registry as deg_registry
from fmeval import REPO
from metrics import registry as metric_registry

from .schema import KINDS, Card, CardError, parse_card

CARD_YAML = "card.yaml"
"""The typed record that marks a directory as a bundle."""

BUNDLE_FILES = (CARD_YAML, "card.md", "refs.bib")
"""Files every bundle must contain, whatever it holds."""

GENERATED_DIR = "_generated"
"""Build output. Never hand-edited; regenerated by ``python -m fmeval.cards``."""

SKIP_ENV = "FMEVAL_SKIP_CARD_CHECK"
"""Set to ``1`` to bypass card validation. For debugging only, and it says so loudly."""


@dataclass(frozen=True)
class Bundle:
    """One bundle directory and the paths inside it."""

    name: str
    kind: str
    path: Path

    @property
    def card_yaml(self) -> Path:
        return self.path / CARD_YAML

    @property
    def card_md(self) -> Path:
        return self.path / "card.md"

    @property
    def generated(self) -> Path:
        return self.path / GENERATED_DIR

    @property
    def fingerprint(self) -> Path:
        """The measured half of a metric's card, written by ``cards evidence``."""
        return self.generated / "fingerprint.json"

    @property
    def implementation(self) -> Path:
        return self.path / ("metric.py" if self.kind == "metric" else "degradation.py")


def bundle_root(kind: str) -> Path:
    """The directory holding all bundles of one kind."""
    if kind not in KINDS:
        raise ValueError(f"unknown bundle kind {kind!r}")
    return REPO / ("metrics" if kind == "metric" else "degradations")


def iter_bundles(kind: str | None = None) -> list[Bundle]:
    """Every bundle on disk, sorted by name.

    A directory counts as a bundle when it contains a ``card.yaml``. Directories whose
    name starts with an underscore are skipped: those are templates and shared helpers,
    which are deliberately not bundles.

    Args:
        kind: ``"metric"``, ``"degradation"``, or ``None`` for both.

    Returns:
        The bundles found, sorted by (kind, name).
    """
    kinds = KINDS if kind is None else (kind,)
    found: list[Bundle] = []
    for k in kinds:
        root = bundle_root(k)
        if not root.is_dir():
            continue
        for entry in sorted(root.iterdir()):
            if not entry.is_dir() or entry.name.startswith(("_", ".")):
                continue
            if (entry / CARD_YAML).is_file():
                found.append(Bundle(name=entry.name, kind=k, path=entry))
    return found


def find_bundle(name: str, kind: str | None = None) -> Bundle | None:
    """The bundle registered under ``name``, or ``None`` if there is no such directory."""
    return next((bundle for bundle in iter_bundles(kind) if bundle.name == name), None)


def load_card(bundle: Bundle) -> Card:
    """Read and validate one bundle's ``card.yaml``.

    Args:
        bundle: The bundle to read.

    Returns:
        The validated card.

    Raises:
        CardError: If the file is missing, unparseable, invalid, or disagrees with the
            directory it sits in.
    """
    path = bundle.card_yaml
    if not path.is_file():
        raise CardError(
            str(path),
            "this bundle has no card, so nothing records what it measures or how to "
            "read its output.",
            f"python -m fmeval.cards new {bundle.name} --kind {bundle.kind}",
        )
    try:
        data = yaml.safe_load(path.read_text()) or {}
    except yaml.YAMLError as exc:
        raise CardError(str(path), f"the file is not valid YAML: {exc}", "fix the syntax") from exc

    card = parse_card(data, where=str(path))

    if card.name != bundle.name:
        raise CardError(
            str(path),
            f"card name is {card.name!r} but the directory is {bundle.name!r}. The name "
            "is the metric's identity and the two must agree.",
            f"rename one of them so both read {bundle.name!r}",
        )
    if card.kind != bundle.kind:
        raise CardError(
            str(path),
            f"card kind is {card.kind!r} but the bundle lives under "
            f"{bundle_root(bundle.kind).name}/.",
            f"set kind: {bundle.kind}",
        )
    return card


def check_bundle_files(bundle: Bundle) -> list[str]:
    """Report which required files a bundle is missing.

    Args:
        bundle: The bundle to inspect.

    Returns:
        Problems as human-readable sentences; empty when the bundle is complete.
    """
    paths = [bundle.path / filename for filename in BUNDLE_FILES] + [bundle.implementation]
    return [f"{path.name} is missing" for path in paths if not path.is_file()]


